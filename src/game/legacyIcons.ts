/** Sélecteur de variante emoji et liant : retirés */
const VARIANT = /\u{FE0F}/gu;
const JOINER = /\u{200D}/gu;
/** Tout autre pictogramme restant (non reconnu) */
const LEFTOVER = /[\u{2190}-\u{21FF}\u{2300}-\u{23FF}\u{25A0}-\u{27BF}\u{2B00}-\u{2BFF}\u{1F000}-\u{1FAFF}]/gu;

export function legacyToIcons(text: string): string {
  let s = text.replace(VARIANT, '');
  // Séquences les plus longues d'abord (emoji composés)
  for (const [emoji, id] of LEGACY) if (s.includes(emoji)) s = s.split(emoji).join(I[id]);
  return s.replace(JOINER, '').replace(LEFTOVER, (c) => (c === '\u{2192}' ? c : ''));
}

/** Applique la conversion à toutes les chaînes d'un objet (notifications et leurs choix) */
export function deepLegacyToIcons<T>(v: T): T {
  if (typeof v === 'string') return legacyToIcons(v) as T;
  if (Array.isArray(v)) return v.map(deepLegacyToIcons) as T;
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, deepLegacyToIcons(x)])) as T;
  return v;
}
